/* Feature parity: IOTC_Session_Get_Channel_ON_Count                     */

int32_t IOTC_Session_Get_Channel_ON_Count(int64_t sid)
{
    SessionEntry *entry = find_session(sid, 0);
    if (!entry)
        return 0;
    uint32_t mask = entry->chan_mask;
    int count = 0;
    for (int i = 0; i < 32; ++i)
        if (mask & (1u << i))
            ++count;
    return count;
}

